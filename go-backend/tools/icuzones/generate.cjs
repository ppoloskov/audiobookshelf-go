#!/usr/bin/env node
// Generates internal/identity/icu_zones_gen.go: the table of zone names that
// Node's ICU canonicalizes to a different name in
// Intl.DateTimeFormat().resolvedOptions().timeZone when TZ=<name>.
// Upstream: server/objects/settings/ServerSettings.js getHostTimeZone.
// Run with Node 22.x from go-backend: node tools/icuzones/generate.cjs
'use strict'

const fs = require('fs')
const path = require('path')
const { spawnSync } = require('child_process')

const ZONEINFO = process.env.ZONEINFO_DIR || '/usr/share/zoneinfo'
const SKIP_DIRS = new Set(['posix', 'right'])
const SKIP_FILES = new Set(['localtime', 'posixrules', 'leapseconds', 'leap-seconds.list'])

function isTZif(file) {
  let fd
  try {
    fd = fs.openSync(file, 'r')
    const buf = Buffer.alloc(4)
    const n = fs.readSync(fd, buf, 0, 4, 0)
    return n === 4 && buf.toString('latin1') === 'TZif'
  } catch {
    return false
  } finally {
    if (fd !== undefined) fs.closeSync(fd)
  }
}

function walk(dir, prefix, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name
    const full = path.join(dir, entry.name)
    let stat
    try {
      stat = fs.statSync(full)
    } catch {
      continue
    }
    if (stat.isDirectory()) {
      if (!prefix && SKIP_DIRS.has(entry.name)) continue
      walk(full, rel, out)
    } else if (!SKIP_FILES.has(entry.name) && !entry.name.endsWith('.tab') && isTZif(full)) {
      out.add(rel)
    }
  }
}

const candidates = new Set(Intl.supportedValuesOf('timeZone'))
walk(ZONEINFO, '', candidates)

// Go's own zone database (GOROOT/lib/time/zoneinfo.zip, the names
// time.LoadLocation accepts everywhere) carries the legacy link names such as
// US/Pacific that minimal /usr/share/zoneinfo trees omit.
function goZipNames() {
  const goroot = spawnSync('go', ['env', 'GOROOT'], { encoding: 'utf8' })
  if (goroot.status !== 0) return []
  const zip = path.join(goroot.stdout.trim(), 'lib', 'time', 'zoneinfo.zip')
  const list = spawnSync('unzip', ['-Z1', zip], { encoding: 'utf8', maxBuffer: 1 << 24 })
  if (list.status !== 0) return []
  return list.stdout.split('\n').filter((n) => n && !n.endsWith('/') && !n.endsWith('.tab'))
}
for (const name of goZipNames()) candidates.add(name)

function resolve(name) {
  const res = spawnSync(process.execPath, ['-e', 'process.stdout.write(Intl.DateTimeFormat().resolvedOptions().timeZone)'], {
    env: { ...process.env, TZ: name },
    encoding: 'utf8'
  })
  if (res.status !== 0) throw new Error(`node failed for TZ=${name}: ${res.stderr}`)
  return res.stdout
}

const entries = []
for (const name of [...candidates].sort()) {
  const got = resolve(name)
  if (got !== name) entries.push([name, got])
}

const q = (s) => JSON.stringify(s)
let src = '// Code generated by tools/icuzones/generate.cjs; DO NOT EDIT.\n'
src += `// node ${process.version}, icu ${process.versions.icu}, tz ${process.versions.tz}\n`
src += `// ${candidates.size} candidate names, ${entries.length} canonicalized.\n\n`
src += 'package identity\n\n'
src += '// icuZones maps a TZ value to the name Node 22 ICU reports for it in\n'
src += '// Intl.DateTimeFormat().resolvedOptions().timeZone. Names absent from the map\n'
src += '// resolve to themselves.\n'
src += 'var icuZones = map[string]string{\n'
for (const [k, v] of entries) src += `\t${q(k)}: ${q(v)},\n`
src += '}\n'

const target = path.join(__dirname, '..', '..', 'internal', 'identity', 'icu_zones_gen.go')
fs.writeFileSync(target, src)
// Keep the output gofmt-clean (aligned map values).
if (spawnSync('gofmt', ['-w', target]).status !== 0) throw new Error('gofmt failed')
console.log(`wrote ${target}: ${entries.length} entries from ${candidates.size} candidates`)
