func TestIsGeneratedSourceNeedsHeaderBeforePackageClause(t *testing.T) {
	cases := map[string]bool{
		"// Code generated by sqlc. DO NOT EDIT.\npackage a\n":              true,
		"// Code generated by mockgen v1. DO NOT EDIT.\r\npackage a\r\n":    true,
		"package a\n// Code generated by sqlc. DO NOT EDIT.\n":              false,
		"// Code generated by sqlc. DO NOT EDIT\npackage a\n":               false,
		"// Code generated by sqlc.\npackage a\n":                           false,
		"// Handwritten. Code generated by sqlc. DO NOT EDIT.\npackage a\n": false,
	}
	for src, want := range cases {
		if got := isGeneratedSource([]byte(src)); got != want {
			t.Errorf("isGeneratedSource(%q) = %v, want %v", src, got, want)
		}
	}
}

func TestSimplificationSkipsGeneratedAndTestFiles(t *testing.T) {
	root := t.TempDir()
	write := func(rel, src string) {
		t.Helper()
		path := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	// 5 lines, one function with complexity 2.
	write("internal/a/a.go", "package a\n\nfunc A(x bool) bool {\n\treturn x && x\n}\n")
	// Generated: skipped entirely, including its branches.
	write("internal/a/gen.go", "// Code generated by sqlc. DO NOT EDIT.\n\npackage a\n\nfunc G() {\n\tif true {\n\t}\n}\n")
	// Test file: skipped.
	write("internal/a/a_test.go", "package a\n\nfunc TestA() {\n\tif true {\n\t}\n}\n")
	// 6 lines, one function with complexity 2, under cmd.
	write("cmd/tool/main.go", "package main\n\nfunc main() {\n\tfor {\n\t}\n}\n")

	counts, funcs, err := measureSimplification(root)
	if err != nil {
		t.Fatal(err)
	}
	if got, want := counts["handwritten Go lines"], 11; got != want {
		t.Errorf("handwritten Go lines = %d, want %d", got, want)
	}
	if got, want := counts["cyclomatic complexity total"], 4; got != want {
		t.Errorf("cyclomatic complexity total = %d, want %d", got, want)
	}
	if got := counts["functions with complexity > 15"]; got != 0 {
		t.Errorf("functions with complexity > 15 = %d, want 0", got)
	}
	if len(funcs) != 2 {
		t.Fatalf("funcs = %v, want 2 entries", funcs)
	}
}

func TestPrintTopOrdersByComplexityThenLocation(t *testing.T) {
	funcs := []funcStat{
		{name: "Small", file: "internal/a.go", line: 3, complexity: 2},
		{name: "Big", file: "internal/b.go", line: 9, complexity: 20},
		{name: "AlsoBig", file: "internal/a.go", line: 30, complexity: 20},
	}
	var out strings.Builder
	printTop(&out, funcs, 2)
	want := "top 2 most complex functions:\n  20  internal/a.go:30  AlsoBig\n  20  internal/b.go:9  Big\n"
	if out.String() != want {
		t.Fatalf("printTop() =\n%q\nwant\n%q", out.String(), want)
	}
}
