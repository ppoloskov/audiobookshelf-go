func parseFuncs(t *testing.T, source string) map[string]*ast.FuncDecl {
	t.Helper()
	file, err := parser.ParseFile(token.NewFileSet(), "fixture.go", source, parser.AllErrors)
	if err != nil {
		t.Fatal(err)
	}
	funcs := map[string]*ast.FuncDecl{}
	for _, decl := range file.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok {
			funcs[funcName(fn)] = fn
		}
	}
	return funcs
}

func TestComplexityMatchesGocycloOnHandComputedFunction(t *testing.T) {
	// Base 1, plus: if and && (2), range (1), if and || (2), two non-default
	// cases (2), one non-default select case (1), && inside a FuncLit (1).
	// Default clauses and the FuncLit itself add nothing. Total 10.
	source := `package p
func F(a, b, c bool, xs []int, ch chan int) int {
	if a && b {
		return 1
	}
	for _, x := range xs {
		if x > 0 || c {
			continue
		}
	}
	switch {
	case a:
	case b:
	default:
	}
	select {
	case <-ch:
	default:
	}
	g := func() bool { return a && c }
	_ = g
	return 0
}
`
	fn := parseFuncs(t, source)["F"]
	if fn == nil {
		t.Fatal("F not found")
	}
	if got, want := complexity(fn), 10; got != want {
		t.Fatalf("complexity(F) = %d, want %d", got, want)
	}
}

