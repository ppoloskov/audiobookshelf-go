#!/usr/bin/env node
'use strict'

const crypto = require('node:crypto')
const fs = require('node:fs')
const path = require('node:path')
const ROOT = path.resolve(__dirname, '../../..')
const RECORD = path.join(ROOT, 'go-backend/contracts/parity/latest-core-run.json')
const STATUS = path.join(ROOT, 'go-backend/STATUS.md')

// Fingerprint executable/test inputs, not generated output or runtime fixtures.
function inputDigest(root = ROOT) {
  const files = ['go-backend/go.mod', 'go-backend/go.sum', 'index.js', 'tsconfig.server.json', 'package.json', 'package-lock.json', 'dist-server/index.js']
  function visit(relative, extensions) {
    for (const entry of fs.readdirSync(path.join(root, relative), { withFileTypes: true })) {
      const name = `${relative}/${entry.name}`
      if (entry.isDirectory()) visit(name, extensions)
      else if (extensions.includes(path.extname(name))) files.push(name)
    }
  }
  for (const dir of ['go-backend/cmd', 'go-backend/internal']) visit(dir, ['.go'])
  visit('go-backend/tools/parity', ['.cjs', '.json', '.py'])
  visit('server', ['.js', '.ts', '.json'])
  visit('dist-server/server', ['.js', '.json'])
  const hash = crypto.createHash('sha256')
  for (const file of files.sort()) hash.update(file).update('\0').update(fs.readFileSync(path.join(root, file))).update('\0')
  return hash.digest('hex')
}

function failedStateChecks(value, prefix = '') {
  if (!value || typeof value !== 'object') return []
  return Object.entries(value).flatMap(([key, child]) => {
    const name = prefix ? `${prefix}.${key}` : key
    if (key === 'equal') return child === true ? [] : [name]
    return failedStateChecks(child, name)
  })
}

function snapshot(report, sourceReport) {
  if (!report.verification?.inputDigest || !report.verification?.completedInputDigest) throw new Error('report lacks execution provenance; run make parity')
  if (report.verification.inputDigest !== report.verification.completedInputDigest) throw new Error('inputs changed during execution; rerun parity')
  if (!report.statefulChecks || typeof report.statefulChecks !== 'object' || Array.isArray(report.statefulChecks)) throw new Error('core report lacks stateful checks')
  if (!Array.isArray(report.cases) || report.cases.length === 0) throw new Error('report must execute nonzero cases')
  const ids = new Set()
  for (const record of report.cases) {
    if (typeof record.id !== 'string' || !record.id || typeof record.passed !== 'boolean') throw new Error('invalid case verdict')
    if (ids.has(record.id)) throw new Error(`duplicate case ID: ${record.id}`)
    ids.add(record.id)
  }
  const summary = {
    total: report.cases.length,
    executed: report.cases.filter(record => !record.skipped).length,
    passed: report.cases.filter(record => record.passed).length,
    failed: report.cases.filter(record => !record.passed && !record.skipped).length,
    skipped: report.cases.filter(record => record.skipped).length
  }
  for (const [key, value] of Object.entries(summary)) {
    if (report.summary?.[key] !== value) throw new Error(`report summary ${key} is inconsistent`)
  }
  if (summary.executed === 0) throw new Error('report must execute nonzero cases')
  return {
    schemaVersion: 1, suite: 'core', baseline: report.baseline,
    generatedAt: report.generatedAt, sourceReport,
    inputDigest: report.verification.inputDigest, summary,
    executionError: report.executionError || null,
    failedStateChecks: [...new Set([
      ...failedStateChecks(report.statefulChecks),
      ...['coverDelete', 'coverUpload', 'coverPatch', 'emailDevices', 'coverURLFailure'].filter(name => report.statefulChecks[name]?.equal !== true),
      ...(report.statefulChecks.coverURLRedirect?.equalFailureState === true ? [] : ['coverURLRedirect.equalFailureState'])
    ])],
    equivalencePassed: report.gate?.equivalencePassed === true,
    gateError: report.gate?.error || (report.gate?.equivalencePassed === true ? null : 'report equivalence was not verified'),
    cases: report.cases.map(({ id, passed, skipped }) => ({ id, passed, skipped: !!skipped }))
  }
}

function render(record, currentDigest) {
  const stale = record.inputDigest !== currentDigest
  const passing = record.equivalencePassed && !record.gateError && !record.executionError && record.summary.failed === 0 && record.summary.skipped === 0 && record.failedStateChecks.length === 0
  const result = stale ? 'STALE — executable inputs changed; rerun `make parity`.' : passing ? 'PASS (sampled core suite only)' : 'FAIL'
  return `# Go backend verification status

Generated by \`make status\`; do not edit. This is the latest recorded core run, not a full-parity or deployment claim.

Current result: ${result}

Recorded run: ${record.generatedAt}

Pinned upstream: \`${record.baseline}\`

| Measure | Count |
| --- | --- |
| Declared/results | ${record.summary.total} |
| Executed | ${record.summary.executed} |
| Passed | ${record.summary.passed} |
| Failed | ${record.summary.failed} |
| Skipped | ${record.summary.skipped} |

Failed state checks: ${record.failedStateChecks.length ? record.failedStateChecks.join(', ') : 'none recorded'}.
Report equivalence: ${record.equivalencePassed ? 'passed' : 'not passed'}.
${record.gateError ? `\nCore gate error: ${record.gateError}\n` : ''}
${record.executionError ? `\nExecution error: ${record.executionError}\n` : ''}
Evidence summary: [latest-core-run.json](contracts/parity/latest-core-run.json).
Input SHA-256: \`${record.inputDigest}\`.
The original detailed report was written to \`${record.sourceReport}\`; temporary reports may expire.

Broader operational suites, browser/mobile acceptance, restore acceptance and unexercised variants are not implied by this result. See [ROADMAP.md](ROADMAP.md) for acceptance and [handover.md](handover.md) for remaining gaps.
`
}

function main(args) {
  const digest = inputDigest()
  if (args.length) {
    if (args.length !== 2 || args[0] !== '--report') throw new Error('usage: status.cjs [--report <provenanced-core-report.json>]')
    const source = path.resolve(args[1])
    const record = snapshot(JSON.parse(fs.readFileSync(source, 'utf8')), source)
    fs.writeFileSync(RECORD, `${JSON.stringify(record, null, 2)}\n`)
  }
  if (!fs.existsSync(RECORD)) throw new Error('no recorded core run; run make parity first')
  const record = JSON.parse(fs.readFileSync(RECORD, 'utf8'))
  fs.writeFileSync(STATUS, render(record, digest))
  console.log(`generated ${STATUS}${record.inputDigest === digest ? '' : ' (stale inputs)'}`)
}

if (require.main === module) {
  try { main(process.argv.slice(2)) } catch (error) { console.error(error.message); process.exitCode = 1 }
}
module.exports = { inputDigest, snapshot, render }
